#!/usr/bin/env node
/**
 * Content-hash cache busting (industry pattern):
 * - HTML stays revalidated (meta + server Cache-Control).
 * - Asset URLs get ?v=<content-hash> so Ctrl+R never mixes old JS/CSS with new HTML.
 * - Compare JSON URL is stamped into js/hlc-data-url.generated.js for the same reason.
 *
 * Usage:
 *   node scripts/stamp-asset-versions.js
 *   node scripts/stamp-asset-versions.js --check
 *   node scripts/stamp-asset-versions.js --write-pages
 */
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const writePages = args.includes("--write-pages");

const DATA_URL_GENERATED = "js/hlc-data-url.generated.js";

/** Layouts (source of truth) → relative asset paths as they appear in href/src. */
const LAYOUT_REFS = [
  {
    file: "templates/layouts/explore-banks.html",
    refs: [
      "../css/shroffin-shell.css",
      "../css/shroffin-explore-banks.css",
      "../js/shroffin-home-stance.js",
      "../js/shroffin-nav.js",
      "../js/hlc-data-url.generated.js",
      "../js/hlc-icon-select.js",
      "../js/home-loan-compare.bundle.js",
      "../js/hlc-field-help.js",
    ],
  },
  {
    file: "templates/layouts/apply.html",
    refs: [
      "../css/shroffin-shell.css",
      "../css/shroffin-apply.css",
      "../js/bank-logos.js",
      "../js/home-loan-apply.js",
      "../js/shroffin-nav.js",
    ],
  },
  {
    file: "templates/layouts/apply-contact.html",
    refs: [
      "../css/shroffin-shell.css",
      "../css/shroffin-apply.css",
      "../js/site-contacts.generated.js",
      "../js/bank-logos.js",
      "../js/home-loan-apply.js",
      "../js/shroffin-nav.js",
    ],
  },
];

function shortHash(absPath) {
  const buf = fs.readFileSync(absPath);
  return crypto.createHash("sha256").update(buf).digest("hex").slice(0, 10);
}

function assetAbsFromRef(ref) {
  // refs are "../css/..." from pages/; map to repo-root relative
  const cleaned = ref.replace(/^\.\.\//, "");
  return path.join(root, cleaned);
}

function stampRef(html, ref, hash) {
  const escaped = ref.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(
    '((?:href|src)="' + escaped + ')(?:\\?v=[^"]*)?(")',
    "g"
  );
  let count = 0;
  const next = html.replace(re, function (_, start, end) {
    count += 1;
    return start + "?v=" + hash + end;
  });
  if (count === 0) {
    throw new Error("No href/src match for " + ref);
  }
  return next;
}

function ensureDataUrlScript(hash) {
  const body =
    "/* Generated by scripts/stamp-asset-versions.js — do not edit */\n" +
    '(function () {\n' +
    '  "use strict";\n' +
    '  window.__HLC_DATA_URL__ = "../data/home-loans-compare.json?v=' +
    hash +
    '";\n' +
    "})();\n";
  const abs = path.join(root, DATA_URL_GENERATED);
  const prev = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (checkOnly) {
    if (prev !== body) {
      console.error(
        "stale " + DATA_URL_GENERATED + " — run: node scripts/stamp-asset-versions.js"
      );
      process.exit(1);
    }
    return;
  }
  if (prev !== body) {
    fs.writeFileSync(abs, body);
    console.log("Wrote " + DATA_URL_GENERATED + " (v=" + hash + ")");
  } else {
    console.log("OK " + DATA_URL_GENERATED + " (v=" + hash + ")");
  }
}

function ensureExploreLayoutHasDataUrlTag(html) {
  if (html.includes("hlc-data-url.generated.js")) return html;
  // Insert before the compare bundle so DATA_URL is set first.
  const needle = '<script src="../js/home-loan-compare.bundle.js';
  if (!html.includes(needle)) {
    throw new Error(
      "explore-banks layout missing home-loan-compare.bundle.js script tag"
    );
  }
  return html.replace(
    needle,
    '<script src="../js/hlc-data-url.generated.js"></script>\n  ' + needle
  );
}

function stampLayout(entry) {
  const abs = path.join(root, entry.file);
  let html = fs.readFileSync(abs, "utf8");
  if (entry.file.indexOf("explore-banks") !== -1) {
    html = ensureExploreLayoutHasDataUrlTag(html);
  }

  entry.refs.forEach(function (ref) {
    const assetPath = assetAbsFromRef(ref);
    if (!fs.existsSync(assetPath)) {
      throw new Error("Missing asset for " + ref + " → " + assetPath);
    }
    const hash = shortHash(assetPath);
    html = stampRef(html, ref, hash);
  });

  const prev = fs.readFileSync(abs, "utf8");
  if (checkOnly) {
    if (prev !== html) {
      console.error(
        "stale asset versions in " +
          entry.file +
          " — run: node scripts/stamp-asset-versions.js"
      );
      process.exit(1);
    }
    console.log("OK " + entry.file);
    return false;
  }

  if (prev !== html) {
    fs.writeFileSync(abs, html);
    console.log("Stamped " + entry.file);
    return true;
  }
  console.log("OK " + entry.file + " (already current)");
  return false;
}

function rebuildFlowPages() {
  const pages = ["explore-banks", "apply", "apply/contact"];
  for (const only of pages) {
    const result = spawnSync(
      process.execPath,
      [
        path.join(root, "scripts", "build-content.js"),
        "--write",
        "--only=" + only,
      ],
      { cwd: root, stdio: "inherit" }
    );
    if (result.status !== 0) process.exit(result.status || 1);
  }
}

function main() {
  const dataHash = shortHash(path.join(root, "data", "home-loans-compare.json"));
  ensureDataUrlScript(dataHash);

  let changed = false;
  LAYOUT_REFS.forEach(function (entry) {
    if (stampLayout(entry)) changed = true;
  });

  if (checkOnly) {
    console.log("check:asset-versions passed");
    return;
  }

  if (writePages || changed) {
    rebuildFlowPages();
  }
}

main();
